    { src: 'images/tiles/stars-fine-glow.png', name: 'stars-fine', tile: true, tileSize: 1000, strength: 0.99 },
    { src: 'images/tiles/stars-open-glow.png', name: 'stars-open', tile: true, tileSize: 1000, strength: 0.94 },
    { src: 'images/tiles/stars-bright-glow.png', name: 'stars-bright', tile: true, tileSize: 1000, strength: 1.07 }
