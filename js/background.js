/* ============================================================
   Layered animated background: Granim gradients + texture wash
   ------------------------------------------------------------
   Builds a self-contained, fixed-position stack behind the page:

     .bgfx                (container, isolate: blending stays inside)
       canvas.bgfx__grad  x N   <- Granim instances, blended together
       div.bgfx__tex      x 2   <- texture slots that cross-fade

   Requires the Granim global (load granim/dist/granim.min.js first).
   Drop-in: import, call createBackground(), keep the returned handle.
   ============================================================ */

/* ---------- palette ----------
   A night sky: indigo, violet, plum, blue, mauve, pink. No warm colours —
   the golds and creams that came from the original stylesheet comment
   (#c5b152, #e7e4d9, #fdfbec) read as daylight and fought the stars. Five
   of that comment's eight survive: #414c90, #9f96bf, #bfced2, #85bfe0,
   #e5f3f8.

   `tier` is perceptual lightness, split at L* 38 and 70, and it's weighted
   toward `deep` on purpose so the sky has somewhere dark to sit. `light` is
   what washes parts of the sky out.

   `family` is a guard rail rather than an active rule right now: every
   colour here is cool, so the same-family constraint on gradients never
   fires. It stays because it's what stops a warm colour, if one is ever
   added back, pairing with its complement and turning the field olive. */

