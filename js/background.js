const DEFAULTS = {
    mount: null,                  // defaults to document.body
    zIndex: -1,
    palette: PALETTE,
    textures: TEXTURES,

    /* One entry per Granim canvas, painted bottom to top.

       Layer 1 owns the color. Its blendMode stays `normal` because nothing
       else can work there: `.bgfx` sets `isolation: isolate`, so the bottom
       layer's backdrop is empty, and blending against an empty backdrop
       returns the source unchanged. Setting it to `soft-light` renders
       identically — verified side by side — so `normal` is what it is.

       Layers 2 and 3 are `soft-light`: a gentle tonal push that keeps most
       of the backdrop's hue. They were `luminosity`, which preserved hue
       exactly and made it impossible to leave the palette; soft-light
       trades that guarantee for warmer, livelier light. The risk it
       reintroduces is a cool layer sitting over a warm base, whose midpoint
       drifts toward olive — mild at these opacities, but if you ever catch
       the field going sage, that's the cause, and `luminosity` on layer 2
       is the cure. */
    layers: [
        {
            direction: 'diagonal', blendMode: 'normal', opacity: 1,
            tiers: ['deep', 'mid', 'light'],
            // At least one stop must have some body, or the field can drift
            // into pale-on-pale and the cards stop reading against it.
            anchorTiers: ['deep', 'mid'],
            speed: [8000, 12000]
        },
        {
            // deep/mid only: letting a modulating layer onto the `light`
            // tier washes the whole field toward white, and pale cards
            // need somewhere darker to sit against.
            direction: 'left-right', blendMode: 'soft-light', opacity: 0.55,
            tiers: ['deep', 'mid'],
            speed: [5000, 8000]
        },
        {
            direction: 'radial', blendMode: 'soft-light', opacity: 0.3,
            tiers: ['deep', 'mid'],
            speed: [13000, 19000]
        }
    ],

    gradientsPerState: 8,         // how many stops before a state is recycled

    /* Minimum L* gap between a gradient's two stops, on a 0-100 scale.
       Low enough that midnight-to-indigo counts as a real gradient; the
       `anchorTiers` rule is what stops both stops being pale. */
    minLightnessGap: 10,

    texture: {
        enabled: true,

        /* One mode only, and deliberately so. Re-rolling the blend mode on
           every texture change was the single biggest cause of swaps
           reading as an event: the mode and its opacity would jump together
           (multiply @0.19 straight into soft-light @0.59), which no amount
           of matching the textures to each other can smooth over. Pinned,
           a change is only ever a change of star field.

           `luminosity` takes the sky's own hue and saturation and lifts it
           to the star's luminance, so the dots glow in whatever colour the
           gradients are currently showing rather than in a fixed white.
           The narrow range keeps consecutive swaps close in weight. */
        blendModes: [
            { mode: 'luminosity', opacity: [0.24, 0.36] }
        ],
        opacity: [0.15, 0.35],    // fallback for modes given as bare strings

        fadeMs: 6000,             // cross-fade duration
        holdMs: [14000, 26000],   // used when syncToGradient is false
        syncToGradient: true,     // change texture when the base layer changes gradient
        everyNChanges: 2,         // ...but only every Nth change

        /* Turns the whole star field about a point, like a sky wheeling
           around a pole. `origin` is a fraction of the viewport, so
           { x: 0.85, y: 0.85 } pivots 15% in from the right and bottom.
           At 600s a full turn is 0.6 deg/sec — roughly 16px/sec at the
           farthest corner and near-still by the pivot. Set to false to
           stop rotating.

           A rotating layer can't be viewport-sized — its corners would sweep
           into view. createBackground() sizes each texture layer to a square
           centred on the pivot, wide enough to still reach the farthest
           viewport corner at every angle, and re-does that on resize. */
        rotate: { seconds: 600, origin: { x: 0.85, y: 0.85 } },

        /* Slow ken-burns, used only when `rotate` is false. The two can't
           run together: both animate `transform`, so the second one declared
           simply wins. Rotation already keeps the field alive. */
        drift: false
    },

    reducedMotion: 'respect'      // 'respect' | 'ignore'
};

/* ---------- small helpers ---------- */

const rand = (min, max) => min + Math.random() * (max - min);
const randInt = (min, max) => Math.floor(rand(min, max + 1));
const pick = arr => arr[Math.floor(Math.random() * arr.length)];

/* CIE L*: perceptual lightness on a 0-100 scale.

   This has to be L* and not relative luminance. Luminance is hopeless at
   separating dark colours: #0d1030 and #2b3468 are obviously different but
   sit 0.033 apart in luminance, while two nearly identical pales sit 0.277
   apart. Ranking by luminance therefore throws out exactly the dark
   gradients this palette is built around. In L* those two pairs measure
   17.5 and 13.2 — the right way round. */
function lightness(hex) {
    const n = parseInt(hex.slice(1), 16);
    const c = [(n >> 16) & 255, (n >> 8) & 255, n & 255].map(v => {
        const s = v / 255;
        return s <= 0.04045 ? s / 12.92 : Math.pow((s + 0.055) / 1.055, 2.4);
    });
    const y = 0.2126 * c[0] + 0.7152 * c[1] + 0.0722 * c[2];
    const d = 6 / 29;
    const f = y > d * d * d ? Math.cbrt(y) : y / (3 * d * d) + 4 / 29;
    return 116 * f - 16;
}

/* A gradient is a two-stop pair drawn from the layer's allowed tiers.

   Three rules, each earning its place:
   - `minGap` rejects pairs too close in L* to read as a gradient at all.
     Measured perceptually, so a midnight-to-indigo pair counts as real
     contrast — which is the whole point of a dark sky.
   - `anchor` forces one stop to come from a narrower set, so a pair
     can't end up pale at both ends.
   - `sameFamily` stops a warm stop pairing with a cool one. Inert while
     the palette is all cool, but it's what kept gold-next-to-blue from
     turning the field sage green, so it stays. */
function makeGradient(pool, minGap, anchor, sameFamily) {
    const anchorPool = anchor && anchor.length ? anchor : pool;
    for (let attempt = 0; attempt < 40; attempt++) {
        const a = pick(anchorPool);
        const partners = sameFamily ? pool.filter(c => c.family === a.family) : pool;
        const b = pick(partners);
        if (!b || a.hex === b.hex) continue;
        if (Math.abs(lightness(a.hex) - lightness(b.hex)) < minGap) continue;
        return Math.random() < 0.5 ? [a.hex, b.hex] : [b.hex, a.hex];
    }
    // Palette too tight for the requested rules: take any distinct pair.
    const a = pick(anchorPool);
    const b = pool.find(c => c.hex !== a.hex) || a;
    return [a.hex, b.hex];
}

function makeGradientSet(pool, count, minGap, anchor, sameFamily) {
    const out = [];
    for (let i = 0; i < count; i++) {
        let g = makeGradient(pool, minGap, anchor, sameFamily);
        // Avoid repeating the previous stop, which reads as a stall.
        let guard = 0;
        while (out.length && g[0] === out[out.length - 1][0] && guard++ < 10) {
            g = makeGradient(pool, minGap, anchor, sameFamily);
        }
        out.push(g);
    }
    return out;
}

/* ============================================================ */

export function createBackground(userOptions = {}) {
    const opts = {
        ...DEFAULTS,
        ...userOptions,
        texture: { ...DEFAULTS.texture, ...(userOptions.texture || {}) }
    };

    if (typeof Granim !== 'function') {
        throw new Error('createBackground: Granim not found. Load granim/dist/granim.min.js before this module.');
    }

    const prefersReduced = opts.reducedMotion === 'respect' &&
        window.matchMedia('(prefers-reduced-motion: reduce)').matches;

    const mount = opts.mount || document.body;

    const root = document.createElement('div');
    root.className = 'bgfx';
    root.style.zIndex = String(opts.zIndex);

    const canvases = opts.layers.map((layer, i) => {
        const c = document.createElement('canvas');
        c.className = 'bgfx__grad';
        c.dataset.layer = String(i);
        c.style.mixBlendMode = layer.blendMode;
        c.style.opacity = String(layer.opacity);
        root.appendChild(c);
        return c;
    });

    const slots = ['a', 'b'].map(name => {
        const d = document.createElement('div');
        d.className = 'bgfx__tex';
        d.dataset.slot = name;
        d.style.transitionDuration = opts.texture.fadeMs + 'ms';
        root.appendChild(d);
        return d;
    });

    mount.appendChild(root);

    /* ---------- rotation geometry ---------- */

    const spin = opts.texture.rotate && !prefersReduced ? opts.texture.rotate : null;

    /* A rotating layer has to reach the farthest viewport corner from the
       pivot, or its own corners swing into view as it turns. Measure all
       four corners rather than assuming which is farthest — that assumption
       only holds while the pivot is in the bottom-right quadrant. */
    function layoutSpinLayers() {
        if (!spin) return;
        const w = root.clientWidth;
        const h = root.clientHeight;
        const ox = w * spin.origin.x;
        const oy = h * spin.origin.y;
        const radius = Math.max(
            Math.hypot(ox, oy),
            Math.hypot(w - ox, oy),
            Math.hypot(ox, h - oy),
            Math.hypot(w - ox, h - oy)
        );
        const side = Math.ceil(2 * radius);
        slots.forEach(s => {
            s.style.width = side + 'px';
            s.style.height = side + 'px';
            s.style.left = (ox - side / 2) + 'px';
            s.style.top = (oy - side / 2) + 'px';
        });
    }

    let resizeRaf = null;
    const onResize = () => {
        cancelAnimationFrame(resizeRaf);
        resizeRaf = requestAnimationFrame(layoutSpinLayers);
    };

    if (spin) {
        layoutSpinLayers();
        window.addEventListener('resize', onResize);
        // Set once, never on texture change: both slots must share a phase,
        // or a cross-fade would show the same sky at two different angles.
        slots.forEach(s => {
            s.style.animation = `bgfx-spin ${spin.seconds}s linear infinite`;
        });
    }

    /* ---------- gradient layers ---------- */

    // Granim caches the per-gradient color maths in `channels`, keyed by
    // state name, so mutating a live state's gradients does nothing after
    // the first pass. Two states let us rebuild the *inactive* one with
    // fresh random gradients, drop its cache, and change into it — which
    // is how the sequence keeps going without ever looping back.
    const instances = opts.layers.map((layer, i) => {
        const inFamily = c => !layer.families || layer.families.includes(c.family);
        const pool = opts.palette.filter(c => layer.tiers.includes(c.tier) && inFamily(c));
        const anchor = layer.anchorTiers
            ? opts.palette.filter(c => layer.anchorTiers.includes(c.tier) && inFamily(c))
            : null;
        const speed = prefersReduced ? rand(...layer.speed) * 3 : rand(...layer.speed);

        const state = () => ({
            gradients: makeGradientSet(pool, opts.gradientsPerState, opts.minLightnessGap, anchor, layer.sameFamily !== false),
            transitionSpeed: speed
        });

        const rec = {
            layer,
            pool,
            anchor,
            speed,
            activeName: 'state-a',
            granim: null
        };

        rec.granim = new Granim({
            element: canvases[i],
            direction: layer.direction,
            defaultStateName: 'state-a',
            stateTransitionSpeed: speed,
            states: { 'state-a': state(), 'state-b': state() },
            onGradientChange: details => {
                if (details.isLooping) recycleState(rec);
                if (i === 0) onBaseGradientChange();
            }
        });

        return rec;
    });

    function recycleState(rec) {
        const next = rec.activeName === 'state-a' ? 'state-b' : 'state-a';
        try {
            rec.granim.states[next] = {
                gradients: makeGradientSet(rec.pool, opts.gradientsPerState, opts.minLightnessGap, rec.anchor, rec.layer.sameFamily !== false),
                transitionSpeed: rec.speed
            };
            // Drop the stale cache so the new colors are actually computed.
            // Safe here: changeState resets the channel index to -1, so the
            // cache refills from 0 in the order Granim expects.
            delete rec.granim.channels[next];
            rec.granim.changeState(next);
            rec.activeName = next;
        } catch (err) {
            // Never let a Granim internals change take the page down —
            // worst case the layer keeps cycling its current gradients.
            console.warn('[bgfx] state recycle skipped:', err);
        }
    }

    /* ---------- texture layers ---------- */

    let visibleSlot = 0;
    let currentTexture = null;
    let textureTimer = null;
    let changeCount = 0;
    let texturesOn = opts.texture.enabled && opts.textures.length > 0;
    let opacityScale = 1;          // live multiplier from the control panel
    let forcedBlend = null;        // null = keep randomising
    let lastApplied = { opacity: 0, blend: 'multiply' };

    /* Entries in texture.blendModes may be a bare mode name or
       { mode, opacity: [lo, hi] }. Either way we come back with a mode and
       the amount of it that reads correctly. */
    function chooseBlend(tex) {
        const entry = forcedBlend
            ? (opts.texture.blendModes.find(m => (m.mode || m) === forcedBlend) || forcedBlend)
            : pick(opts.texture.blendModes);
        const blend = entry.mode || entry;
        const range = entry.opacity || opts.texture.opacity;
        const strength = (tex && tex.strength) || 1;
        return { blend, baseOpacity: rand(...range) * strength };
    }

    function applyTexture(tex, { immediate = false } = {}) {
        const incoming = slots[1 - visibleSlot];
        const outgoing = slots[visibleSlot];

        incoming.style.backgroundImage = `url("${tex.src}")`;
        if (tex.tile) {
            incoming.style.backgroundRepeat = 'repeat';
            incoming.style.backgroundSize = `${tex.tileSize}px auto`;
        } else {
            incoming.style.backgroundRepeat = 'no-repeat';
            incoming.style.backgroundSize = 'cover';
        }
        incoming.style.backgroundPosition = `${randInt(0, 100)}% ${randInt(0, 100)}%`;

        const { blend, baseOpacity } = chooseBlend(tex);
        incoming.style.mixBlendMode = blend;

        // When rotating, leave the animation alone: it was set once at
        // creation, and both slots have to stay on the same phase or a
        // cross-fade shows the same sky at two different angles.
        if (!spin) {
            // Drift is a slow ken-burns; restarting it on each swap keeps
            // the two slots from marching in lockstep.
            incoming.style.animation = 'none';
            if (opts.texture.drift && !prefersReduced) {
                void incoming.offsetWidth; // force reflow so the restart takes
                const dur = randInt(70, 130);
                const dir = Math.random() < 0.5 ? 'normal' : 'reverse';
                incoming.style.animation = `bgfx-drift ${dur}s ease-in-out ${dir} infinite alternate`;
            }
        }

        const fade = opts.texture.fadeMs + 'ms';
        incoming.style.transitionDuration = immediate ? '0ms' : fade;
        outgoing.style.transitionDuration = immediate ? '0ms' : fade;

        lastApplied = { opacity: baseOpacity, blend };

        // Flush the pending style so the browser has a committed "from" value
        // to transition out of. Reading computed style does that synchronously;
        // deferring to requestAnimationFrame would not, because rAF is
        // suspended whenever the tab is backgrounded — the fade would simply
        // never happen and the texture would stay invisible.
        void getComputedStyle(incoming).opacity;
        incoming.style.opacity = String(baseOpacity * opacityScale);
        outgoing.style.opacity = '0';

        if (immediate) {
            void getComputedStyle(incoming).opacity;  // commit the snap...
            incoming.style.transitionDuration = fade; // ...before re-arming the fade
            outgoing.style.transitionDuration = fade;
        }

        visibleSlot = 1 - visibleSlot;
        currentTexture = tex;
    }

    function nextTexture(options) {
        if (!texturesOn) return;
        const choices = opts.textures.filter(t => t !== currentTexture);
        applyTexture(pick(choices.length ? choices : opts.textures), options);
        armTextureTimer();
    }

    function armTextureTimer() {
        clearTimeout(textureTimer);
        if (!texturesOn || opts.texture.syncToGradient) return;
        textureTimer = setTimeout(nextTexture, rand(...opts.texture.holdMs));
    }

    function onBaseGradientChange() {
        if (!texturesOn || !opts.texture.syncToGradient) return;
        changeCount++;
        if (changeCount % Math.max(1, opts.texture.everyNChanges) === 0) nextTexture();
    }

    if (texturesOn) nextTexture({ immediate: true });

    /* ---------- public handle ---------- */

    return {
        root,
        instances: instances.map(r => r.granim),

        pause() {
            instances.forEach(r => r.granim.pause());
            clearTimeout(textureTimer);
            // The rotation is a CSS animation on the compositor, so it keeps
            // turning unless it's paused explicitly.
            slots.forEach(sl => { sl.style.animationPlayState = 'paused'; });
        },
        play() {
            instances.forEach(r => r.granim.play());
            armTextureTimer();
            slots.forEach(sl => { sl.style.animationPlayState = ''; });
        },

        nextTexture: () => nextTexture(),

        /* 0 = textures off, 1 = the configured range, >1 = heavier */
        setTextureIntensity(scale) {
            opacityScale = scale;
            slots[visibleSlot].style.opacity = String(lastApplied.opacity * scale);
        },

        /* Pass null to go back to randomising the blend mode. Re-derives the
           opacity too, so switching multiply -> soft-light doesn't leave the
           texture stuck at an amount tuned for the other mode. */
        setTextureBlend(mode) {
            forcedBlend = mode;
            if (!mode) return;
            const { blend, baseOpacity } = chooseBlend(currentTexture);
            lastApplied = { opacity: baseOpacity, blend };
            slots[visibleSlot].style.mixBlendMode = blend;
            slots[visibleSlot].style.opacity = String(baseOpacity * opacityScale);
        },

        setTexturesEnabled(on) {
            texturesOn = on && opts.textures.length > 0;
            if (!texturesOn) {
                clearTimeout(textureTimer);
                slots.forEach(s => { s.style.opacity = '0'; });
            } else {
                nextTexture();
            }
        },

        setLayerOpacity(index, value) {
            if (canvases[index]) canvases[index].style.opacity = String(value);
        },

        setLayerBlend(index, mode) {
            if (canvases[index]) canvases[index].style.mixBlendMode = mode;
        },

        /* Multiply every layer's transition speed. 1 = as configured. */
        setSpeedScale(scale) {
            instances.forEach(r => {
                const s = r.speed / scale;
                r.granim.states['state-a'].transitionSpeed = s;
                r.granim.states['state-b'].transitionSpeed = s;
                r.granim.activetransitionSpeed = s;
                r.granim.stateTransitionSpeed = s;
            });
        },

        /* What the current look actually is, ready to paste into a config. */
        describe() {
            return {
                layers: instances.map((r, i) => {
                    const gradients = r.granim.states[r.activeName].gradients;
                    const at = r.granim.channelsIndex;
                    return {
                        direction: r.layer.direction,
                        blendMode: canvases[i].style.mixBlendMode,
                        opacity: Number(canvases[i].style.opacity),
                        tiers: r.layer.tiers,
                        transitionSpeed: Math.round(r.granim.activetransitionSpeed),
                        // The pair actually on screen right now — this is the one
                        // you want when you've just seen a look worth keeping.
                        current: [gradients[at], gradients[(at + 1) % gradients.length]],
                        gradients
                    };
                }),
                texture: currentTexture ? {
                    src: currentTexture.src,
                    blendMode: lastApplied.blend,
                    opacity: Number((lastApplied.opacity * opacityScale).toFixed(3))
                } : null
            };
        },

        destroy() {
            clearTimeout(textureTimer);
            cancelAnimationFrame(resizeRaf);
            window.removeEventListener('resize', onResize);
            instances.forEach(r => { try { r.granim.destroy(); } catch (e) { /* already gone */ } });
            root.remove();
        }
    };
}

export default createBackground;
